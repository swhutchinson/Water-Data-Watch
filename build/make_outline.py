# Turns the ONS boundary of North West England into a drawing the map can use, on the same grid as the sampling points.
# Run once, by hand, when the boundary changes: python build/make_outline.py <boundary.geojson>

# Reads the boundary file
import json
# Reads the file's path from the command line
import sys
# Handles file paths
from pathlib import Path

# Converts latitude and longitude to the British National Grid
from pyproj import Transformer

# Converts from longitude and latitude to easting and northing
TO_GRID = Transformer.from_crs("EPSG:4326", "EPSG:27700", always_xy=True)
# Reads the boundary
shape = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))["features"][0]["geometry"]
# The file's polygons, whichever way it stores them
polygons = shape["coordinates"] if shape["type"] == "MultiPolygon" else [shape["coordinates"]]
# The pieces of the drawing
parts = []
# Each polygon: the mainland and the islands
for polygon in polygons:
    # The outer edge and any holes
    for ring in polygon:
        # Each corner, on the grid in units of 100 metres, with north pointing up the page
        corners = [(round(e / 100), -round(n / 100)) for e, n in (TO_GRID.transform(lon, lat) for lon, lat in ring)]
        # Drops corners that land on the one before, which would only add length
        corners = [c for i, c in enumerate(corners) if i == 0 or c != corners[i - 1]]
        # Adds this ring to the drawing
        parts.append("M" + "L".join(f"{e},{n}" for e, n in corners) + "Z")
# Saves it where the map's chart can import it
out = Path(__file__).resolve().parent / "specs" / "nw_outline.mjs"
# Writes the file, with its source stated
out.write_text("// North West England, on the National Grid in units of 100 m, with north up the page. Generated by build/make_outline.py.\n// Source: Office for National Statistics licensed under the Open Government Licence v.3.0. Contains OS data © Crown copyright and database right.\nexport const NW_OUTLINE = " + json.dumps("".join(parts)) + ";\n", encoding="utf-8")
# Says how big it is
print(len(parts), "rings,", out.stat().st_size, "bytes")
